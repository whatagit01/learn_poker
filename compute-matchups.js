// Exact equity by full enumeration of every runout. Writes ../matchups.js
// Run with: node tools/compute-matchups.js
const fs = require("fs");
const path = require("path");

const PE = require("../poker-eval.js");
const equity = (h1, h2, board = []) => PE.equityExact(h1.map(PE.parse), h2.map(PE.parse), board.map(PE.parse));

const PREFLOP = [
  { name: "Big pair vs smaller pair", hero: ["A♠", "A♥"], villain: ["K♣", "K♦"], note: "Overpair vs underpair is about 4-to-1, whichever pairs they are." },
  { name: "Pair vs two overcards (the classic 'coin flip')", hero: ["Q♠", "Q♥"], villain: ["A♣", "K♦"], note: "Called a coin flip, but the pair is a small favourite." },
  { name: "Small pair vs two overcards", hero: ["2♠", "2♥"], villain: ["A♣", "K♦"], note: "Even 22 is a slight favourite against AK." },
  { name: "Pair vs one overcard", hero: ["J♠", "J♥"], villain: ["A♣", "10♦"], note: "About 70/30 for the pair." },
  { name: "Dominated: same ace, worse kicker", hero: ["A♠", "K♥"], villain: ["A♣", "Q♦"], note: "Domination is roughly 3-to-1. The worse kicker needs to pair it." },
  { name: "Two overcards vs two undercards", hero: ["A♠", "K♥"], villain: ["Q♣", "J♦"], note: "Two higher cards vs two lower is about 60/40, not a lock." },
  { name: "Big cards vs suited connector", hero: ["A♠", "K♥"], villain: ["7♣", "6♣"], note: "Suited connectors keep around 40% against AK." },
  { name: "Aces vs a suited connector", hero: ["A♠", "A♥"], villain: ["8♣", "7♣"], note: "Even aces only win about 4 in 5 against a hand like this." },
];

const FLOP = [
  { name: "Set vs overpair", hero: ["8♠", "8♦"], villain: ["K♠", "K♥"], board: ["Q♣", "8♥", "3♠"], note: "The overpair needs a K (or runner-runner). It's in deep trouble." },
  { name: "Overpair vs top pair", hero: ["Q♠", "Q♦"], villain: ["J♣", "10♥"], board: ["J♠", "6♦", "2♣"], note: "Top pair has 5 outs (two pair or trips)." },
  { name: "Top pair, better kicker", hero: ["A♣", "K♥"], villain: ["K♠", "Q♦"], board: ["K♦", "7♠", "2♥"], note: "Kicker domination: the worse kicker has only 3 outs." },
  { name: "Top pair vs flush draw", hero: ["K♠", "Q♣"], villain: ["7♥", "6♥"], board: ["K♥", "9♥", "2♣"], note: "A flush draw wins about 35–40% with two cards to come (backdoor straights add a little)." },
  { name: "Top pair vs nut flush draw + overcard", hero: ["K♠", "Q♣"], villain: ["A♥", "4♥"], board: ["K♥", "9♥", "2♣"], note: "Adding an overcard to the draw makes it close to a flip." },
  { name: "Top pair vs open-ended straight draw", hero: ["A♠", "J♣"], villain: ["9♣", "8♦"], board: ["J♥", "10♠", "2♣"], note: "8 outs is roughly 1-in-3 by the river." },
  { name: "Top pair vs combo draw", hero: ["A♠", "J♣"], villain: ["9♥", "8♥"], board: ["J♥", "10♥", "2♣"], note: "Flush draw + open-ender (15 outs) is the favourite against top pair!" },
  { name: "Top pair vs gutshot", hero: ["A♠", "Q♣"], villain: ["9♣", "8♦"], board: ["Q♥", "J♠", "3♦"], note: "4 outs is about 1-in-6 by the river." },
  { name: "Pair vs two overcards", hero: ["8♣", "8♦"], villain: ["A♠", "K♦"], board: ["7♠", "4♦", "2♥"], note: "Two overcards have 6 outs, about 1-in-4." },
];

// Multiway: how a hand's preflop all-in equity drops as more random opponents join.
const MULTIWAY_HANDS = [["A♠", "A♥"], ["K♠", "K♥"], ["A♠", "K♠"], ["A♠", "K♥"], ["J♠", "10♠"], ["7♠", "6♠"], ["2♠", "2♥"]];
const MW_ITERS = 200000;

const out = { preflop: [], flop: [], multiway: [] };
for (const m of PREFLOP) { process.stdout.write("."); out.preflop.push({ ...m, ...equity(m.hero, m.villain) }); }
for (const m of FLOP) { process.stdout.write("."); out.flop.push({ ...m, ...equity(m.hero, m.villain, m.board) }); }
for (const h of MULTIWAY_HANDS) {
  process.stdout.write(".");
  const vs = [];
  for (let n = 1; n <= 5; n++) vs.push(PE.equityVsRandom(h.map(PE.parse), [], n, MW_ITERS));
  out.multiway.push({ hand: h, vs });
}
const round = (o) => JSON.stringify(o, (k, v) => (typeof v === "number" ? Math.round(v * 10000) / 10000 : v), 2);
fs.writeFileSync(path.join(__dirname, "..", "matchups.js"),
  `/* Generated by tools/compute-matchups.js. Heads-up figures are exact (every runout); multiway figures are Monte Carlo (${MW_ITERS.toLocaleString("en-GB")} deals each, ±0.3%). Do not edit by hand. */\n` +
  `(function (root) {\n  const data = ${round(out).replace(/\n/g, "\n  ")};\n` +
  `  if (typeof module !== "undefined" && module.exports) module.exports = data;\n  else root.PokerMatchups = data;\n})(typeof window !== "undefined" ? window : this);\n`);
console.log("\n");
for (const k of ["preflop", "flop"]) for (const m of out[k]) console.log(`${(m.equity * 100).toFixed(1).padStart(5)}%  ${m.hero.join("")} vs ${m.villain.join("")} ${m.board ? m.board.join("") : ""}  ${m.name}`);
for (const m of out.multiway) console.log(m.hand.join(""), m.vs.map((x) => (x * 100).toFixed(1) + "%").join("  "));
